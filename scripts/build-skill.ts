/**
 * Embed the agent skill(s) in the Worker so archibase.dev can serve them: every file individually
 * (/skills/<name>/<path>) and as a zip (/skills/<name>.zip). Run after editing anything in skills/:
 *
 *   npm run build:skill
 *
 * tests/skill.test.ts fails if src/site/skill-bundle.ts is out of date. The zip is deterministic
 * (sorted entries, fixed timestamps), so rebuilding without changes produces the same bytes.
 */
import { spawnSync } from "node:child_process";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("../skills/", import.meta.url).pathname;
const names = readdirSync(root).filter((n) => statSync(join(root, n)).isDirectory()).sort();

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? walk(join(dir, f)) : [join(dir, f)])).sort();
}

const skills: Record<string, { description: string; files: Record<string, string>; zip: string }> = {};
for (const name of names) {
  const dir = join(root, name);
  const files: Record<string, string> = {};
  for (const f of walk(dir)) files[relative(dir, f)] = readFileSync(f, "utf8");
  const front = /^---\n([\s\S]*?)\n---/.exec(files["SKILL.md"] ?? "");
  const description = /^description:\s*(.+)$/m.exec(front?.[1] ?? "")?.[1]?.trim();
  if (!description) throw new Error(`${name}/SKILL.md needs a frontmatter description`);

  // Deterministic zip via Python's standard library.
  const py = `
import base64, io, json, sys, zipfile
files = json.load(sys.stdin)
buf = io.BytesIO()
with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
    for path in sorted(files):
        info = zipfile.ZipInfo(sys.argv[1] + "/" + path, date_time=(2026, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = (0o755 if path.endswith(".mjs") else 0o644) << 16
        z.writestr(info, files[path].encode("utf8"))
print(base64.b64encode(buf.getvalue()).decode())
`;
  const r = spawnSync("python3", ["-I", "-c", py, name], { input: JSON.stringify(files), encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  if (r.status !== 0) throw new Error(`zip failed: ${r.stderr}`);
  skills[name] = { description, files, zip: r.stdout.trim() };
}

writeFileSync(
  new URL("../src/site/skill-bundle.ts", import.meta.url),
  "// Generated by scripts/build-skill.ts from skills/. Do not edit by hand.\n" +
    "export interface SkillBundle { description: string; files: Record<string, string>; zip: string }\n" +
    `export const SKILLS: Record<string, SkillBundle> = ${JSON.stringify(skills)};\n`,
);
console.log(`wrote src/site/skill-bundle.ts: ${names.join(", ")} (${Object.values(skills).map((s) => Object.keys(s.files).length + " files, zip " + Math.round((s.zip.length * 3) / 4 / 1024) + " KB").join("; ")})`);
