/**
 * Embed the browser scripts in the Worker: reads src/site/client/*.js and writes src/site/client-bundle.ts.
 * Run after editing a client script:   npm run build:client
 * (tests/site.test.ts fails if the bundle is out of date.)
 */
import { readFileSync, writeFileSync } from "node:fs";

const files = { EXPLORE_JS: "explore.js" } as const;
let out = "// Generated by scripts/build-client.ts from src/site/client/*.js. Do not edit by hand.\n";
for (const [name, file] of Object.entries(files)) {
  let src: string;
  try {
    src = readFileSync(new URL(`../src/site/client/${file}`, import.meta.url), "utf8").replace(/\r\n?/g, "\n");
  } catch {
    continue; // script not written yet
  }
  out += `export const ${name} = ${JSON.stringify(src)};\n`;
}
writeFileSync(new URL("../src/site/client-bundle.ts", import.meta.url), out);
console.log("wrote src/site/client-bundle.ts");
