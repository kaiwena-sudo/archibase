/**
 * Generate src/site/og.ts: the 1200x630 social preview image (/og.png), as base64.
 * Run after build-site-example.ts:   npx tsx scripts/build-og-image.ts
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { GALLERY } from "../src/site/example.js";

const { chromium } = createRequire(import.meta.url)("playwright") as typeof import("playwright");

const plan = GALLERY[0]!.svg;
const html = `<!doctype html><html><head><meta charset="utf-8"><style>
*{box-sizing:border-box}body{margin:0;width:1200px;height:630px;background:#f7f6f2;color:#1b1d21;font-family:ui-sans-serif,system-ui,-apple-system,"Segoe UI",Roboto,sans-serif;display:grid;grid-template-columns:600px 600px}
.l{padding:72px 0 64px 72px;display:flex;flex-direction:column;justify-content:space-between}
.brand{display:flex;align-items:center;gap:14px;font-weight:700;font-size:30px}
.brand svg{width:38px;height:38px}
h1{font-size:46px;line-height:1.05;letter-spacing:-.02em;margin:0}
p{font-size:24px;color:#5d6370;margin:0;line-height:1.4}
.r{display:flex;align-items:center;justify-content:center;padding:48px}
.card{background:#fff;border:1px solid #d9d6cc;border-radius:18px;padding:24px;width:100%}
.card svg{width:100%;height:auto;display:block}
.room{stroke:#2a2d33;stroke-width:2;fill:#fff}.r-balcony{fill:#ececec}.r-bedroom{fill:#dce8fb}.r-bathroom{fill:#dcf1e4}.r-kitchen{fill:#fbe9d0}.r-living{fill:#efe4f6}
.door{fill:#9a6a3a}.entrance{fill:#d0402b}.window{fill:#1f4fd1}.scale{stroke:#1b1d21;stroke-width:3}
.lbl{font:600 12px ui-sans-serif,system-ui,sans-serif;fill:#1b1d21;text-anchor:middle}.area{font:11px ui-monospace,Menlo,monospace;fill:#5d6370;text-anchor:middle}
</style></head><body>
<div class="l">
  <div class="brand"><svg viewBox="0 0 32 32"><path d="M4 4h24v24H4z" fill="none" stroke="#1b1d21" stroke-width="3"/><path d="M4 16h12v12M16 4v8" fill="none" stroke="#1f4fd1" stroke-width="3"/></svg>Archibase</div>
  <div><h1>The only structured, license-clean, machine-native floorplan corpus.</h1></div>
  <p>Built for spatial AI, generative design,<br>and architecture agents</p>
</div>
<div class="r"><div class="card">${plan}</div></div>
</body></html>`;

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1200, height: 630 }, deviceScaleFactor: 1 });
await page.setContent(html);
const png = await page.screenshot({ type: "png" });
await browser.close();
writeFileSync(
  new URL("../src/site/og.ts", import.meta.url),
  `// Generated by scripts/build-og-image.ts. Do not edit by hand.\nexport const OG_PNG_BASE64 = ${JSON.stringify(png.toString("base64"))};\n`,
);
writeFileSync(new URL("../og-preview.png", import.meta.url), png);
console.log(`wrote src/site/og.ts (${png.length} bytes)`);
